"""Необязательный импорт записей из старого library.db (SQLite) в PostgreSQL.

Перед запуском настройте файл .env и один раз запустите: python -m pip install -r requirements.txt
Затем выполните: python migrate_sqlite_to_postgres.py
Импортируются книги, которых ещё нет в PostgreSQL по комбинации title + author.
"""
from pathlib import Path
import sqlite3
from app import connect_db

base_dir = Path(__file__).resolve().parent
sqlite_path = base_dir / "library.db"
if not sqlite_path.exists():
    raise SystemExit("Файл library.db не найден. Положите сюда старый SQLite-файл или пропустите импорт.")

source = sqlite3.connect(sqlite_path)
source.row_factory = sqlite3.Row
books = source.execute("SELECT title, author, year, genre FROM books ORDER BY id").fetchall()
source.close()

inserted = 0
with connect_db() as target:
    target.execute("""CREATE TABLE IF NOT EXISTS books (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title VARCHAR(150) NOT NULL,
        author VARCHAR(120) NOT NULL,
        year INTEGER CHECK (year IS NULL OR (year >= 1 AND year <= 2100)),
        genre VARCHAR(60) NOT NULL DEFAULT 'Без жанра',
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""")
    for book in books:
        result = target.execute(
            "SELECT id FROM books WHERE title = %s AND author = %s LIMIT 1",
            (book["title"], book["author"]),
        ).fetchone()
        if result is None:
            target.execute(
                "INSERT INTO books (title, author, year, genre) VALUES (%s, %s, %s, %s)",
                (book["title"], book["author"], book["year"], book["genre"]),
            )
            inserted += 1
print(f"Импорт завершён. Добавлено книг: {inserted}; найдено в SQLite: {len(books)}.")
